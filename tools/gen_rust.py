"""Generate prost structs for a set of root messages (plus their dependencies).

Usage: python3 gen_rust.py schema_full.json Msg1 Msg2 ... > ../core/src/rootapi/proto.rs
Unknown / map fields are omitted (prost skips unknown tags when decoding),
enums are plain i32, and wrapper types (StringValue, Int32Value, Timestamp)
are generated like any other message.
"""
import json, sys, re

schema = json.load(open(sys.argv[1]))
roots = sys.argv[2:]
by_short = {}
for full in schema:
    by_short.setdefault(full.split(".")[-1], []).append(full)

def resolve(short):
    c = by_short.get(short, [])
    for pref in ("root.", "root.v2.", "connect.", "google.protobuf."):
        for f in c:
            if f.startswith(pref):
                return f
    return c[0] if c else None

# Well-known types are not in the bundle schema; define them.
WELL_KNOWN = {
    "StringValue": [{"no": 1, "name": "value", "type": "string"}],
    "Int32Value": [{"no": 1, "name": "value", "type": "int32"}],
    "Int64Value": [{"no": 1, "name": "value", "type": "int64"}],
    "BoolValue": [{"no": 1, "name": "value", "type": "bool"}],
    "Timestamp": [{"no": 1, "name": "seconds", "type": "int64"}, {"no": 2, "name": "nanos", "type": "int32"}],
    "Empty": [],
}
SCALARS = {"string": "string", "bool": "bool", "int32": "int32", "int64": "int64", "uint32": "uint32",
           "uint64": "uint64", "sint32": "sint32", "sint64": "sint64", "fixed32": "fixed32", "fixed64": "fixed64",
           "sfixed32": "sfixed32", "sfixed64": "sfixed64", "float": "float", "double": "double", "bytes": "bytes"}
RUST = {"string": "String", "bool": "bool", "int32": "i32", "int64": "i64", "uint32": "u32", "uint64": "u64",
        "sint32": "i32", "sint64": "i64", "fixed32": "u32", "fixed64": "u64", "sfixed32": "i32", "sfixed64": "i64",
        "float": "f32", "double": "f64", "bytes": "Vec<u8>"}
KEYWORDS = {"type", "match", "ref", "move", "self", "struct", "enum", "fn", "use", "mod", "loop", "where", "async", "await"}

def fields_of(short):
    if short in WELL_KNOWN:
        return WELL_KNOWN[short]
    full = resolve(short)
    return schema.get(full) if full else None

done, order, queue = set(), [], list(roots)
while queue:
    s = queue.pop()
    if s in done:
        continue
    flds = fields_of(s)
    if flds is None:
        continue
    done.add(s)
    order.append(s)
    for f in flds:
        t = f.get("type")
        if t and t not in SCALARS and t not in ("unknown", "map") and not f.get("enum"):
            queue.append(t)

print("// @generated by tools/gen_rust.py from Root's protobuf schema. Do not edit by hand.")
print("#![allow(clippy::all, dead_code)]")
print()
for s in sorted(order):
    print("#[derive(Clone, PartialEq, ::prost::Message)]")
    print(f"pub struct {s} {{")
    for f in sorted(fields_of(s), key=lambda f: f["no"]):
        t = f.get("type")
        name = f["name"]
        if name in KEYWORDS:
            name = "r#" + name
        rep = bool(f.get("repeat"))
        if t in ("unknown", "map", None):
            continue
        if f.get("enum"):
            attr = f'#[prost(int32, {"repeated, " if rep else ""}tag = "{f["no"]}")]'
            print(f"    {attr}\n    pub {name}: {'Vec<i32>' if rep else 'i32'},")
            continue
        if t not in SCALARS and fields_of(t) is None:
            # Unresolvable type: omit rather than guess (prost skips unknown tags safely).
            continue
        if t in SCALARS:
            attr = f'#[prost({SCALARS[t]}, {"repeated, " if rep else ""}tag = "{f["no"]}")]'
            print(f"    {attr}\n    pub {name}: {'Vec<' + RUST[t] + '>' if rep else RUST[t]},")
        else:
            if rep:
                print(f'    #[prost(message, repeated, tag = "{f["no"]}")]\n    pub {name}: Vec<{t}>,')
            else:
                print(f'    #[prost(message, optional, tag = "{f["no"]}")]\n    pub {name}: Option<{t}>,')
    print("}")
    print()
print(f"// {len(order)} messages", file=sys.stderr)
